// scripts/generate-image-manifest.mjs
//
// Scans src/assets/images/* and emits a typed manifest of the keys actually
// present on disk. The manifest is consumed by imageRegistry.ts to turn
// "added an element/weapon/character but forgot the image" from a silent
// runtime `undefined` into a compile error.
//
// Run after adding/removing image assets:  npm run gen:images

import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const IMAGES_DIR = resolve(__dirname, '../src/assets/images');
const OUT_FILE = resolve(__dirname, '../src/modules/shared/infrastructure/imageRegistry.manifest.ts');

// folder → how to strip a filename down to its manifest key.
const GROUPS = [
    { folder: 'profile', name: 'Profile', suffix: '_Profile.webp' },
    { folder: 'wish', name: 'Wish', suffix: '_Wish.png' },
    { folder: 'element', name: 'Element', suffix: '_White.svg' },
    { folder: 'weapon', name: 'Weapon', suffix: '.webp' },
];

function keysFor({ folder, suffix }) {
    return readdirSync(resolve(IMAGES_DIR, folder))
        .filter((file) => file.endsWith(suffix))
        .map((file) => file.slice(0, -suffix.length))
        .sort();
}

const blocks = GROUPS.map((group) => {
    const keys = keysFor(group);
    const constName = `${group.name.toUpperCase()}_IMAGE_KEYS`;
    const typeName = `${group.name}ImageKey`;
    const literals = keys.map((key) => `    '${key}',`).join('\n');
    return [
        `export const ${constName} = [`,
        literals,
        `] as const;`,
        `export type ${typeName} = (typeof ${constName})[number];`,
    ].join('\n');
});

const banner = [
    '// src/modules/shared/infrastructure/imageRegistry.manifest.ts',
    '//',
    '// GENERATED by scripts/generate-image-manifest.mjs — do not edit by hand.',
    '// Run `npm run gen:images` after changing image assets.',
    '',
].join('\n');

writeFileSync(OUT_FILE, `${banner}${blocks.join('\n\n')}\n`);

const counts = GROUPS.map((group) => `${group.folder}: ${keysFor(group).length}`).join(', ');
console.log(`image manifest written → ${OUT_FILE}\n  ${counts}`);
